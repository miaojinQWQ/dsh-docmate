// Build the single-file Client bundle for dsh-docmate.
//
//   node build.mjs           → writes ./client.js
//   node build.mjs --check   → also runs `node --check client.js`
//
// Every src/client/NN-*.js is a plain script fragment (no import/export, no top-level
// await). They are concatenated in filename order inside one factory body, so a module
// may only rely on the `React` argument and on globals it defines itself.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(here, 'src', 'client');
const out = path.join(here, 'client.js');

const files = (await readdir(srcDir))
  .filter((name) => /^\d\d-[\w.-]+\.js$/.test(name))
  .sort((a, b) => a.localeCompare(b, 'en'));

if (files.length === 0) throw new Error('no src/client/NN-*.js fragments found');

const parts = [];
for (const name of files) {
  const body = await readFile(path.join(srcDir, name), 'utf8');
  parts.push(`\n/* ── ${name} ─────────────────────────────────────────── */\n${body.trimEnd()}\n`);
}

const banner = `/* dsh-docmate — generated by build.mjs; edit src/client/*.js instead. */
`;

const bundle = `${banner}window.__ModuleLoader__.load({
  id: 'dsh-docmate',
  factory(require) {
    const React = require('react');
${parts.join('')}
    return createPlugin(React);
  },
});
`;

await writeFile(out, bundle, 'utf8');
const kb = (Buffer.byteLength(bundle) / 1024).toFixed(1);
console.log(`[build] ${files.length} fragments → ${path.relative(here, out)} (${kb} KiB)`);

if (process.argv.includes('--check')) {
  execFileSync(process.execPath, ['--check', out], { stdio: 'inherit' });
  console.log('[build] syntax OK');
}
